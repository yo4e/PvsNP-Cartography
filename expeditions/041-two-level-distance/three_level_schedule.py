"""Enumerate seed-to-leaf *labels* at k=10, a=3 (no field or symbol evaluator).

H is the four-element XOR subgroup generated by 9 and 18. Every tree node's
edge labels are local coordinate words. Non-leaf fresh bits are enumerated.
"""
from collections import Counter, defaultdict
from itertools import combinations
import json


A = 3
H = (0, 9, 18, 27)


def require(condition, reason):
    if not condition:
        raise ValueError(reason)


def descend(dimension, seed, path=()):
    """Branch directly on the BV14 down rule. Erase duplicate labels only at the end."""
    if dimension <= 2*A:
        yield path, dimension
        return
    low_width = dimension // 2
    high, low = divmod(seed, 1 << low_width)
    for fresh in range(1 << A):
        row_seed = low | (fresh << low_width)
        yield from descend(low_width + A, row_seed, path + (("R", high),))
    for fresh in range(1 << (A - 1)):
        column = low | (fresh << low_width)
        yield from descend(dimension - low_width, high, path + (("C", column),))


def translated_leaf_union(seed, single_covers):
    return frozenset().union(*(single_covers[seed ^ delta] for delta in H))


def check_one_seed(z, leaves):
    v = z >> 5
    outer_cols = set()
    middle_cols = set()
    bottom = defaultdict(lambda: {"R": set(), "C": set()})
    for path, dim in leaves:
        edge, label = path[0]
        if edge == "C":
            require(len(path) == 1 and dim == 5, "outer column did not terminate in dimension 5")
            outer_cols.add(label)
        else:
            require(label == v, "translations crossed the selected outer row")
            edge2, label2 = path[1]
            if edge2 == "C":
                require(len(path) == 2 and dim == 4, "middle column did not terminate in dimension 4")
                middle_cols.add(label2)
            else:
                edge3, label3 = path[2]
                require(len(path) == 3 and dim == {"R": 6, "C": 4}[edge3],
                        "unexpected leaf at bottom of selected row")
                bottom[label2][edge3].add(label3)

    require(outer_cols == {((z ^ h) & 31) + 32*f for h in H for f in range(4)},
            "outer groups or indexing mismatch")
    require(middle_cols == {((z ^ h) & 15) + 16*f for h in H for f in range(4)},
            "incomplete middle columns")
    require(set(bottom) == set(range(16)), "some middle row absent")
    col_sizes = []
    for middle_row, families in bottom.items():
        require(families["R"] == set(range(16)), "bottom row missing")
        expected = {((z ^ h) & 7) + 8*f for h in H for f in range(4)
                    if (((z ^ h) >> 4) & 1) == middle_row % 2}
        require(families["C"] == expected and len(expected) >= 8,
                "bottom rectangle has insufficient abscissas")
        col_sizes.append(len(expected))
    return (len(outer_cols), len(middle_cols), len(bottom), min(col_sizes), max(col_sizes))


def check_outer_counts():
    # Any orbit-invariant low-index set is a union of the eight H-orbits.
    # At the outer root each low-index group labels four separate columns.
    orbits = sorted({tuple(sorted(u ^ h for h in H)) for u in range(32)})
    require(len(orbits) == 8 and all(len(orbit) == 4 for orbit in orbits), "wrong orbit partition")
    cases = Counter()
    for size in range(9):
        for subset in combinations(orbits, size):
            indices = {u for group in subset for u in group}
            columns = {u + 32*f for u in indices for f in range(4)}
            if len(indices) <= 4:
                require(32*len(indices) <= 128, "sparse count exceeded")
                cases["sparse"] += 1
            else:
                require(len(indices) >= 8 and len(columns) >= 32,
                        "not enough outer common columns to interpolate")
                cases["at_least_32_columns"] += 1
    return dict(sorted(cases.items()))


def main():
    require({a ^ b for a in H for b in H} == set(H), "masks do not form subgroup")
    single = [frozenset(descend(10, z)) for z in range(1024)]
    regular = Counter()
    counts = set()
    rejected_coset = []
    rejected_zero = 0
    chosen = 7
    # In the all-zero extension with one nonzero external coset, the only
    # candidate bad leaves are bottom rows of selected outer v and (middle j,
    # bottom i) = (0 or 1, 0 or 1). These labels contain the descended parent
    # sites. Their field-word verdict (eight ones, 56 zeros) is separate.
    marked_rows = {((("R", chosen), ("R", j), ("R", i)), 6)
                   for j in (0, 1) for i in (0, 1)}
    no_bad_leaves = frozenset()
    for z in range(1024):
        leaves = translated_leaf_union(z, single)
        regular[check_one_seed(z, leaves)] += 1
        counts.add(len(leaves))
        require(all(leaves == translated_leaf_union(z ^ h, single) for h in H),
                "orbit does not preserve physical leaf-label set")
        rejected_zero += int(bool(leaves & no_bad_leaves))
        if leaves & marked_rows:
            rejected_coset.append(z)
    require(rejected_zero == 0 and rejected_coset == list(range(32*chosen, 32*(chosen + 1))),
            "wrong rejection incidence for marked leaf rows")
    require(len(regular) == 1 and counts == {416}, "nonuniform cover counts")
    (outer_columns, middle_columns, middle_rows, low, high), = regular
    return {"scope": "leaf labels and supplied failure-pattern incidence; no field predicates executed",
            "root_dimension": 10, "translations": H,
            "seed_count": len(single), "distinct_leaf_labels_per_seed_union": 416,
            "outer_rows_per_seed": 1, "outer_columns_per_seed": outer_columns,
            "middle_rows_per_selected_outer_row": middle_rows,
            "middle_columns_per_selected_outer_row": middle_columns,
            "bottom_rows_per_selected_middle_row": 16,
            "bottom_columns_per_selected_middle_row_min_max": [low, high],
            "outer_orbit_union_counts": check_outer_counts(),
            "no_bad_leaf_rejections": rejected_zero, "single_marked_outer_coset": chosen,
            "four_marked_bottom_rows_rejected_seeds": rejected_coset}


if __name__ == "__main__":
    print(json.dumps(main(), indent=2, sort_keys=True))
